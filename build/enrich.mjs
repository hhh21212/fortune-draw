// 修正源站标题中的错别字/赘字，去掉「古人」前缀与尾部标点
const TITLE_FIX = {
  26: '梁灏大器晚成',
  51: '孙膑被害',
  57: '金星戏窦儿',
  67: '张飞战张郃',
  69: '伍子胥走难',
  70: '海瑞中进士',
  76: '六出祁山',
  79: '庄子鼓盆歌',
  82: '泥马渡康王',
  87: '孔子在陈',
  90: '祭李彦贵',
};
function cleanTitle(t, id) {
  let s = (TITLE_FIX[id] || t).replace(/^古人/, '').replace(/[。．.、，,]+$/g, '').trim();
  return s;
}

const data = raw.map((r) => {
  const j = J[r.id];
  if (!j) throw new Error(`缺第${r.id}签的吉凶`);
  return { id: r.id, title: cleanTitle(r.title, r.id), poem: r.poem, level: j[0], brief: j[1] };
});

